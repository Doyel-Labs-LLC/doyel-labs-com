import { access, mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve("src", "app");
const paths = [];
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === "admin" || entry.name.startsWith("_")) continue;
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(file);
    else if (entry.name === "page.tsx") {
      const relative = path.relative(root, directory).split(path.sep).join("/");
      if (/[[\]()@]/.test(relative)) throw new Error("Public analytics paths need explicit static-route generation.");
      paths.push(relative ? `/${relative}/` : "/");
    }
  }
}
await collect(root);
await writeFile(path.resolve("src", "lib", "public-paths.generated.ts"),
  `// Generated from static pages; package-admin verifies the published export.\nexport const publishedPaths: readonly string[] = ${JSON.stringify(paths.sort())};\n`);

// Typecheck-time placeholder; scripts/package-admin.mjs writes the real file at build.
const adminAssets = path.resolve("server", "analytics", "admin-assets.generated.ts");
try {
  await access(adminAssets);
} catch {
  await mkdir(path.dirname(adminAssets), { recursive: true });
  await writeFile(adminAssets, "// Placeholder until `npm run build` packages the admin export.\nexport const adminAssets: Record<string, { content: string; contentType: string; scriptHashes: string }> = {};\nexport const publicPaths: string[] = [];\n");
}

// Image slots: list files in public/media/generated so <Photo> can pick them
// up without touching the filesystem at render time.
const generatedDir = path.resolve("public", "media", "generated");
let generated = [];
try {
  generated = (await readdir(generatedDir)).filter((name) => /\.(?:jpg|jpeg|webp|png)$/i.test(name)).sort();
} catch {
  generated = [];
}
await writeFile(path.resolve("src", "lib", "generated-images.generated.ts"),
  `// Generated by scripts/generate-public-paths.mjs from public/media/generated.\nexport const generatedImages: readonly string[] = ${JSON.stringify(generated)};\n`);
